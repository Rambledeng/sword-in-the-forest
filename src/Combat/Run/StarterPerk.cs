namespace SwordInTheForest.Run
{
    /// <summary>
    /// A new soul's minor trait: a weaker form of one sword-intent upgrade, picked once per soul
    /// (see <see cref="StarterPerks"/>).
    /// </summary>
    public enum StarterPerk
    {
        /// <summary>A little more health (Vitality, smaller).</summary>
        Hale,
        /// <summary>A slightly larger posture bar (Broad Stance, smaller).</summary>
        Sturdy,
        /// <summary>Posture recovers a little faster (Steady Breath, smaller).</summary>
        EvenBreath,
        /// <summary>One more gourd sip per area (Deep Gourd).</summary>
        SpareSip,
        /// <summary>Deflects deal a little more posture damage (Iron Deflect, smaller).</summary>
        SteadyHand,
    }
}
